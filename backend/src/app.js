import { createFacilityService } from './modules/facilities/service.js';
import { createBookingService } from './modules/bookings/service.js';
import { bookingRoutes } from './modules/bookings/routes.js';
import { createBookingSeriesService } from './modules/bookings/series-service.js';
import { recurringCreateRoutes, customerSeriesRoutes, ownerSeriesRoutes } from './modules/bookings/series-routes.js';
import { paymentRoutes } from './modules/payments/routes.js';
import { createPaymentService } from './modules/payments/service.js';
import { createProofStorage } from './modules/payments/storage.js';
import { createOwnerPaymentService } from './modules/payments/owner-service.js';
import { ownerPaymentRoutes } from './modules/payments/owner-routes.js';
import { createRefundService } from './modules/refunds/service.js';
import { refundRoutes } from './modules/refunds/routes.js';
import { createPublicFacilityService } from './modules/facilities/public/service.js';
import { publicFacilityRoutes } from './modules/facilities/public/routes.js';
import { createRecurringSearchService } from './modules/facilities/recurring/service.js';
import { facilityRoutes } from './modules/facilities/routes.js';
import { createCourtService } from './modules/courts/service.js';
import { createAvailabilityService } from './modules/courts/availability/service.js';
import { availabilityRoutes } from './modules/courts/availability/routes.js';
import { courtRoutes } from './modules/courts/routes.js';
import { createBookingConfigurationService } from './modules/facilities/booking-configuration/service.js';
import { bookingConfigurationRoutes } from './modules/facilities/booking-configuration/routes.js';
import { createPresentationService } from './modules/facilities/presentation/service.js';
import { presentationRoutes } from './modules/facilities/presentation/routes.js';
import { createImageStorage } from './modules/facilities/presentation/storage.js';
import express from 'express';
import cors from 'cors';
import { env } from './config/env.js';
import { createHealthRoutes } from './routes/index.js';
import { prisma } from './config/prisma.js';
import { createAuthService } from './modules/auth/service.js';
import { authRoutes, apiError } from './modules/auth/routes.js';
import { createResetEmail } from './modules/auth/email.js';
import { createGoogleOAuth } from './modules/auth/google.js';
import { createOwnerRequestService } from './modules/users/owner-requests/service.js';
import { ownerRequestRoutes } from './modules/users/owner-requests/routes.js';
import { createProfileService } from './modules/users/profile/service.js';
import { profileRoutes } from './modules/users/profile/routes.js';
import { createOwnerAnalyticsService } from './modules/analytics/owner-service.js';
import { ownerAnalyticsRoutes } from './modules/analytics/owner-routes.js';

export function createApp(db = prisma, config = env, limits, emailAdapter = createResetEmail(config), facilityDistricts, imageStorage = createImageStorage(), imageLogger = console, proofStorage = createProofStorage(), proofLogger = console) {
  if (config.nodeEnv === 'production' && (!config.frontendUrl.startsWith('https://') || new URL(config.frontendUrl).origin !== config.frontendUrl)) throw new Error('PRODUCTION_FRONTEND_ORIGIN_INVALID');
  const app = express();
  app.use(cors({ origin: config.frontendUrl, credentials: true }));
  app.use(express.json({ limit: '16kb' }));
  app.use('/api/v1', createHealthRoutes(db));
  app.use('/api/v1/courts', availabilityRoutes(createAvailabilityService(db)));
  app.use('/api/v1/facilities', publicFacilityRoutes(createPublicFacilityService(db, imageStorage), createRecurringSearchService(db, imageStorage)));
  const authService = createAuthService(db, emailAdapter);
  const auth = authRoutes(authService, config, limits, createGoogleOAuth(config));
  app.locals.passwordTasks = auth.passwordTasks;
  app.use('/api/v1/auth', auth);
  const series = createBookingSeriesService(db, proofStorage);
  app.use('/api/v1/bookings/recurring', recurringCreateRoutes(series, authService, config));
  app.use('/api/v1/booking-series', customerSeriesRoutes(series, authService, config));
  app.use('/api/v1/bookings', bookingRoutes(createBookingService(db, proofStorage, { flowVersion: config.bookingFlowVersion }), authService, config));
  app.use('/api/v1/owner/booking-series', ownerSeriesRoutes(series, authService, config));
  app.use('/api/v1/owner/analytics', ownerAnalyticsRoutes(createOwnerAnalyticsService(db), authService));
  app.use('/api/v1/payments', paymentRoutes(createPaymentService(db, proofStorage, proofLogger), authService, config));
  app.use('/api/v1/owner', ownerPaymentRoutes(createOwnerPaymentService(db, proofStorage), authService, config));
  const refunds = createRefundService(db, proofStorage, proofLogger);
  app.use('/api/v1/refunds', refundRoutes(refunds, authService, config));
  app.use('/api/v1/owner/refunds', refundRoutes(refunds, authService, config, true));
  const ownerRequests = createOwnerRequestService(db);
  app.use('/api/v1/users/me/owner-requests', ownerRequestRoutes(ownerRequests, authService, config));
  app.use('/api/v1/users/me', profileRoutes(createProfileService(db), authService, config));
  app.use('/api/v1/admin/owner-requests', ownerRequestRoutes(ownerRequests, authService, config, true));
  const facilities = createFacilityService(db, facilityDistricts);
  const presentation = createPresentationService(db, imageStorage, imageLogger);
  app.use('/api/v1/owner', presentationRoutes(presentation, authService, config));
  app.use('/api/v1/admin', presentationRoutes(presentation, authService, config, true));
  app.use('/api/v1/owner/facilities', bookingConfigurationRoutes(createBookingConfigurationService(db, proofStorage, proofLogger), authService, config));
  app.use('/api/v1/owner', courtRoutes(createCourtService(db), authService, config));
  app.use('/api/v1/owner/facilities', facilityRoutes(facilities, authService, config));
  app.use('/api/v1/admin/facilities', facilityRoutes(facilities, authService, config, true));
  app.use(apiError);
  return app;
}
const app = createApp();

export default app;
